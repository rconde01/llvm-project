def emit_translation_unit(
    tu: IRTranslationUnit, *, shared_header: str | None = None
) -> str:
    """Render the whole translation unit to a single C++ source string.

    When ``shared_header`` is given (multi-file projects), the shared
    structs — derived types, module state, common blocks — are assumed to
    live in that header (see :func:`emit_shared_header`); this file just
    ``#include``\\s it instead of re-defining them.
    """
    out = StringIO()
    _emit_file_header(out, tu)
    _emit_includes(out, tu, shared_header=shared_header)
    if shared_header is None:
        # Single-file: all structs, constants and prototypes live here.
        _emit_module_constants(out, tu)
        _emit_derived_types(out, tu)
        _emit_module_structs(out, tu)
        _emit_common_structs(out, tu)
        _emit_local_state_structs(out, tu)
        _emit_prototypes(out, tu)
    # With a shared header the structs and prototypes are declared there;
    # this file only carries the routine definitions.  A procedure-taking
    # routine is a template, though, and a template's definition must be
    # visible at every call site — so those live in the shared header
    # (emit_shared_header), not here.  In single-file mode (no shared
    # header) everything is one TU, so templates are defined here as usual.
    for sub in tu.subprograms:
        if shared_header is not None and _is_template_sub(sub):
            continue
        out.write("\n")
        _emit_subprogram(out, sub)
    _emit_cpp_main(out, tu)
    return out.getvalue()


def emit_shared_header(tu: IRTranslationUnit, *, guard: str) -> str:
    """Render everything a multi-file project's files share: derived
    types, module / common / per-routine state structs, and every
    subprogram prototype.  Included by every generated ``.cpp`` so
    cross-file references and calls resolve to one set of definitions."""
    out = StringIO()
    out.write("// Generated by fortran-to-cpp (shared module/type header).\n")
    out.write("// Edit the original Fortran source rather than this file.\n\n")
    out.write(f"#ifndef {guard}\n#define {guard}\n\n")
    out.write("#include <functional>\n")
    out.write('#include "fortran/runtime.hpp"\n')
    out.write("\nusing namespace std::string_view_literals;\n")
    # Constants first — array bounds in the structs below may use them.
    _emit_module_constants(out, tu)
    _emit_derived_types(out, tu)
    _emit_module_structs(out, tu)
    _emit_common_structs(out, tu)
    _emit_local_state_structs(out, tu)
    _emit_prototypes(out, tu)
    # Procedure-taking routines are function templates: their definitions
    # must be visible wherever they're called, so they live here in the
    # shared header (the per-file ``.cpp`` skips them).  Prototypes above
    # already forward-declare them, so a template that calls another
    # template resolves regardless of definition order.
    seen: set[str] = set()
    for sub in tu.subprograms:
        if not _is_template_sub(sub) or sub.name in seen:
            continue
        seen.add(sub.name)
        out.write("\n")
        _emit_subprogram(out, sub)
    out.write(f"\n#endif  // {guard}\n")
    return out.getvalue()


def _emit_derived_types(out: StringIO, tu: IRTranslationUnit) -> None:
    if not tu.derived_types:
        return
    out.write("\n// ---- User-defined types ----\n")
    for dt in tu.derived_types:
        out.write(f"\nstruct {dt.cpp_type} {{\n")
        for field_local in dt.fields:
            _emit_local(out, field_local, indent=1, storage="struct")
        out.write("};\n")


def _emit_module_constants(out: StringIO, tu: IRTranslationUnit) -> None:
    """Module ``PARAMETER``\\s are compile-time constants — emit them as
    file/header-scope ``inline constexpr`` so they can be referenced
    without a module instance (in routine bodies, array bounds, and even
    workspace/derived-type struct fields)."""
    params = [(m, v) for m in tu.modules for v in m.variables if v.is_parameter]
    if not params:
        return
    out.write("\n// ---- Module parameters (compile-time constants) ----\n")
    for _, var in params:
        _emit_local(out, var, indent=0, storage="namespace")


def _emit_module_structs(out: StringIO, tu: IRTranslationUnit) -> None:
    # Only mutable module variables become struct members; PARAMETERs are
    # emitted as free constants by ``_emit_module_constants``.
    modules = [
        m for m in tu.modules if any(not v.is_parameter for v in m.variables)
    ]
    if not modules:
        return
    out.write("\n// ---- Module state structs (module variables) ----\n")
    for m in modules:
        out.write(f"\nstruct {m.cpp_type} {{\n")
        for var in m.variables:
            if not var.is_parameter:
                _emit_local(out, var, indent=1, storage="struct")
        out.write("};\n")


def _emit_common_structs(out: StringIO, tu: IRTranslationUnit) -> None:
    if tu.common_structs:
        out.write("\n// ---- Common block structs (shared program state) ----\n")
        for s in tu.common_structs:
            _emit_one_struct(out, s)


def _emit_local_state_structs(out: StringIO, tu: IRTranslationUnit) -> None:
    """Per-subprogram state (SAVE locals, workspaces) — these belong with
    the routine's definition, so they stay in the routine's own file.

    Deduplicated by struct name: a utility routine duplicated across
    several files (common in old code) yields several subprograms with
    the same workspace/save struct, which must be defined only once."""
    seen: set[str] = set()

    def emit_unique(structs: list[IRStateStruct]) -> None:
        for s in structs:
            if s.cpp_type not in seen:
                seen.add(s.cpp_type)
                _emit_one_struct(out, s)

    save_structs = [
        s.save_struct for s in tu.subprograms if s.save_struct is not None
    ]
    if save_structs:
        out.write("\n// ---- Per-subprogram state structs (SAVE locals) ----\n")
        emit_unique(save_structs)
    workspaces = [s.workspace for s in tu.subprograms if s.workspace is not None]
    if workspaces:
        out.write(
            "\n// ---- Per-subprogram workspaces (hoisted local arrays, "
            "allocated once) ----\n"
        )
        emit_unique(workspaces)


def _emit_one_struct(out: StringIO, s: IRStateStruct) -> None:
    out.write(f"\nstruct {s.cpp_type} {{\n")
    for field_local in s.fields:
        # Reuse the local-declaration emitter so types and defaults
        # stay consistent.
        _emit_local(out, field_local, indent=1, storage="struct")
    out.write("};\n")


