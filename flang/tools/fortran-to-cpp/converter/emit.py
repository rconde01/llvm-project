def _proc_param_indices(sub: IRSubprogram) -> list[int]:
    """Positions of ``sub``'s dummy-procedure parameters."""
    return [i for i, p in enumerate(sub.parameters) if p.type.is_procedure]


def _is_template_sub(sub: IRSubprogram) -> bool:
    """A routine that takes a dummy procedure is emitted as a function
    template: each procedure parameter becomes a deduced type ``F<k>``
    rather than a fixed ``std::function``.  This sidesteps cross-program
    signature inference entirely — the compiler deduces the callback type
    from whatever is actually passed, and a forwarded callback keeps its
    (already deduced) type down the chain.  (Procedure *actuals* are wrapped
    in a generic lambda at the call site so even a higher-order routine
    passed as a callback is a concrete object the deduction can latch onto.)"""
    return sub.kind != "main" and bool(_proc_param_indices(sub))


def _template_prefix(sub: IRSubprogram) -> str:
    """``template <class F0, class F1, ...>`` for a procedure-taking
    routine, one type parameter per dummy procedure; ``""`` otherwise."""
    n = len(_proc_param_indices(sub))
    if not n:
        return ""
    return "template <" + ", ".join(f"class F{k}" for k in range(n)) + ">\n"


def _signature(sub: IRSubprogram, *, with_defaults: bool = True) -> str:
    if sub.kind == "function" and sub.return_type is not None:
        ret = sub.return_type.cpp
    else:
        ret = "void"
    # State parameters first (D2.b — granular per-routine state), then the
    # user-visible Fortran dummy args.  Default arguments live on the
    # prototype only (a C++ default may be specified once) and only on the
    # trailing run of OPTIONAL params — C++ forbids a defaulted parameter
    # before a non-defaulted one (Fortran allows optionals anywhere).
    parts = [f"{sp.struct_type}& {sp.name}" for sp in sub.state_params]
    params = sub.parameters
    default_from = len(params)
    for i in range(len(params) - 1, -1, -1):
        if params[i].optional:  # optional scalar (=nullopt) or array (={})
            default_from = i
        else:
            break
    # A procedure-taking routine is a template; render each dummy procedure
    # as its deduced type ``const F<k>&`` instead of a concrete std::function.
    proc_pos = {idx: k for k, idx in enumerate(_proc_param_indices(sub))}
    for i, p in enumerate(params):
        if i in proc_pos:
            parts.append(f"const F{proc_pos[i]}& {p.name}")
        else:
            parts.append(
                p.cpp_param_decl(with_default=with_defaults and i >= default_from)
            )
    return f"{ret} {sub.name}({', '.join(parts)})"



def _emit_prototypes(out: StringIO, tu: IRTranslationUnit) -> None:
    """Forward-declare every subprogram so definitions can appear in any
    order (and mutually recursive routines work)."""
    subs = [s for s in tu.subprograms if s.kind != "main"]
    if not subs:
        return
    out.write("\n// ---- Forward declarations ----\n")
    seen: set[str] = set()  # a routine duplicated across files: declare once
    for sub in subs:
        if sub.name in seen:
            continue
        seen.add(sub.name)
        out.write(f"{_template_prefix(sub)}{_signature(sub)};\n")


def _emit_equiv_group(out: StringIO, g, idx: int) -> None:
    """Render one EQUIVALENCE class as a local struct + bindings.

    Layout (the SPICE pattern -- all members share offset 0):
        struct <CppType> {
          alignas(<A>) std::byte _store[<N>]{};
          fortran::EquivSlot<T,0>  scalar { _store };
          fortran::EquivArray<T,N,0> arr  { _store };
          fortran::FortranString<L> chr;      // character member (special-cased)
        } _eqK;
        auto& <name> = _eqK.<name>;
    The CHARACTER alias is emitted as a plain ``FortranString<L>`` --
    the shared bytes form a single character record, and Fortran code
    addresses it as a substring.
    """
    pad = "  "
    out.write(f"{pad}struct {g.cpp_type} {{\n")
    out.write(f"{pad}  alignas({g.alignment}) std::byte _store[{g.byte_size}]{{}};\n")
    for m in g.members:
        if m.is_character:
            out.write(
                f"{pad}  fortran::FortranString<{m.count}> {m.name};\n"
            )
        elif m.count is None:
            out.write(
                f"{pad}  fortran::EquivSlot<{m.cpp_elem_type}, 0> "
                f"{m.name}{{_store}};\n"
            )
        else:
            out.write(
                f"{pad}  fortran::EquivArray<{m.cpp_elem_type}, "
                f"{m.count}, 0> {m.name}{{_store}};\n"
            )
    out.write(f"{pad}}} _eq{idx};\n")
    for m in g.members:
        out.write(f"{pad}auto& {m.name} = _eq{idx}.{m.name};\n")


def _emit_subprogram(out: StringIO, sub: IRSubprogram) -> None:
    _emit_comment_block(out, sub.leading_comments, indent=0)
    # The prototype carries default arguments; the definition omits them.
    out.write(_template_prefix(sub))
    out.write(_signature(sub, with_defaults=False))
    out.write(" {\n")

    # Emission order: state-*instance* locals (the ``Mod mod{}`` objects
    # the bindings refer to) first, then the bindings, then ordinary
    # locals.  This lets an ordinary local that captures a bound name —
    # notably a statement-function lambda using a COMMON/module variable
    # (``auto f = [&]{ ... re ... }`` with ``auto& re = parmb.re``) — see
    # the binding, which would otherwise be declared after it.
    def _is_state_instance(loc: IRLocal) -> bool:
        return isinstance(loc.initializer, IRRaw) and loc.initializer.text == "{}"

    instance_locals = [loc for loc in sub.locals if _is_state_instance(loc)]
    other_locals = [loc for loc in sub.locals if not _is_state_instance(loc)]
    for loc in instance_locals:
        _emit_local(out, loc, indent=1)

    # EQUIVALENCE classes: one struct per group holding the shared byte
    # buffer plus a typed proxy per aliased Fortran name, then a binding
    # so the body refers to each name unqualified.
    for idx, g in enumerate(sub.equiv_groups):
        _emit_equiv_group(out, g, idx)

    # State bindings: ``auto& field = param.field;`` so the body can use
    # plumbed common / save / module / workspace state by its original
    # name and stay clean.  Param-bindings must come early (before
    # ordinary locals, in case a local's initializer captures one);
    # local-to-local aliases (an empty ``param``, the same-type
    # EQUIVALENCE renaming) must come *after* the canonical local has
    # been declared, so emit those last.
    param_bindings = [b for b in sub.state_bindings if b.param]
    alias_bindings = [b for b in sub.state_bindings if not b.param]
    for b in param_bindings:
        if b.view is not None:
            # Reshaped view of a shared COMMON field (storage association).
            # Two flavours:
            #   * ArrayRef<...>(field.data() + N, ...) -- an array sub-view;
            #     ArrayRef has value semantics (cheap pointer + bounds), so
            #     bind by value.
            #   * field(N) -- a scalar reference to one canonical element
            #     (the routine declares it as a scalar at a fixed byte
            #     offset inside an array canonical, e.g. ``ST0`` at C1(1)).
            #     Bind by reference so writes through the canonical (e.g.
            #     RECALC updating C1) are visible to this routine's name.
            if b.view.lstrip().startswith("fortran::ArrayRef<"):
                out.write(f"  auto {b.name} = {b.view};\n")
            else:
                out.write(f"  auto& {b.name} = {b.view};\n")
        else:
            out.write(f"  auto& {b.name} = {b.param}.{b.field};\n")

    for loc in other_locals:
        _emit_local(out, loc, indent=1)

    for b in alias_bindings:
        out.write(f"  auto& {b.name} = {b.field};\n")

    if (sub.locals or sub.state_bindings) and sub.body:
        out.write("\n")

    # Body.
    for stmt in sub.body:
        _emit_statement(out, stmt, indent=1)

    # For a function with no explicit return: emit one based on the
    # local variable that shared the function name (which lowering
    # has already renamed to ``<name>_result``).
    if sub.kind == "function" and sub.return_type is not None:
        if not _ends_with_return(sub.body):
            if sub.body:
                out.write("\n")
            out.write(f"  return {sub.name}_result;\n")

    out.write("}\n")


def _is_scalar_constant(expr: object) -> bool:
    """True for a scalar constant expression — a literal or a unary
    op (e.g. negation) over one.  Used to recognize a whole-array scalar
    initializer (``= -9999.0``) versus an array-valued initializer (an
    array constructor or an elementwise expression)."""
    if isinstance(expr, IRLiteral):
        return True
    if isinstance(expr, IRUnaryOp):
        return _is_scalar_constant(expr.operand)
    return False


def _try_static_lower_literals(
    lower_exprs: tuple[str, ...],
) -> tuple[int, ...] | None:
    """Parse a tuple of per-dimension lower-bound expressions; return the
    integer values if every entry is a literal integer (optionally signed),
    else ``None``.  Used to decide whether a local owning array should be
    emitted as ``Array<T, R, std::array<index_t, R>{...}>`` (compile-time
    lower bounds: indexing math constant-folds the subtraction) rather than
    the runtime ``Array<T, R>`` form."""
    if not lower_exprs:
        return None
    values: list[int] = []
    for expr in lower_exprs:
        s = expr.strip()
        # Strip an outer (...) -- the converter sometimes wraps a signed
        # literal in parens via the operator-precedence layer.
        while s.startswith("(") and s.endswith(")"):
            inner = s[1:-1].strip()
            # Only strip when the outer parens are matched at the top level
            # (no early closing).  Easy check for our well-formed input.
            if inner.count("(") == inner.count(")"):
                s = inner
            else:
                break
        if s.startswith(("-", "+")):
            sign, body = s[0], s[1:].lstrip()
        else:
            sign, body = "+", s
        # Strip any trailing C++ literal suffix (uUlL).
        while body and body[-1] in "uUlL":
            body = body[:-1]
        if not body.isdigit():
            return None
        values.append(int(sign + body))
    return tuple(values)


def _static_lower_cpp_type(loc: "IRLocal") -> str | None:
    """Return the ``Array<T, R, std::array{...}>`` spelling for ``loc`` when
    every declared lower bound is a literal integer; ``None`` when the
    runtime form is required (no explicit bounds, or some bound is a
    non-literal expression).  Caller still uses the runtime form when this
    returns ``None``."""
    if not loc.type.is_array:
        return None
    lbs = _try_static_lower_literals(loc.type.array_lower_bound_exprs)
    if lbs is None:
        return None
    rank = loc.type.array_rank
    if len(lbs) != rank:
        return None
    # Render the C++ ``std::array<index_t, R>{lbs...}`` NTTP and substitute
    # it for the trailing ``>`` of the runtime spelling.  The runtime cpp is
    # ``fortran::Array<T, R>`` (or similar with namespace prefix).
    cpp = loc.type.cpp
    if not cpp.endswith(">"):
        return None
    inner = ",".join(str(v) for v in lbs)
    nttp = f"std::array<fortran::index_t, {rank}>{{{inner}}}"
    # Splice the NTTP in before the closing ``>``.
    return cpp[:-1] + f", {nttp}>"


def _emit_local(
    out: StringIO, loc: IRLocal, *, indent: int, storage: str = "local"
) -> None:
    pad = "  " * indent
    _emit_comment_block(out, loc.leading_comments, indent=indent)
    # PARAMETER constants: scalars of literal type can be ``constexpr``;
    # arrays (``fortran::Array`` — a non-literal type, often with a
    # runtime-evaluated initializer) must fall back to ``const``.  The
    # storage qualifier depends on where the declaration lives:
    #   * ``local``     — a function-body variable (no extra qualifier);
    #   * ``struct``    — a data member (``static`` / ``static inline``);
    #   * ``namespace`` — a file/header-scope constant (``inline`` so the
    #                     definition is shared across translation units).
    if loc.is_parameter:
        if loc.type.is_array:
            prefix = {
                "local": "const ",
                "struct": "static inline const ",
                "namespace": "inline const ",
            }[storage]
        else:
            prefix = {
                "local": "constexpr ",
                "struct": "static constexpr ",
                "namespace": "inline constexpr ",
            }[storage]
    else:
        prefix = ""
    # An assumed-length CHARACTER *array* local (an ENTRY-shared dummy of a
    # sibling entry, not this entry's argument) is a character-array view,
    # not an owning ``Array<std::string_view>`` — which isn't a real type.
    # Emit a null ``CharArrayRef`` so element/substring access type-checks;
    # the code that uses it is unreachable for this entry.
    if (
        loc.type.is_array
        and loc.type.element_type_cpp == "std::string_view"
        and loc.type.array_rank == 1
    ):
        out.write(f"{pad}{prefix}fortran::CharArrayRef {loc.name}{{}};")
        _emit_trailing(out, loc.trailing_comments)
        return
    if (
        loc.type.is_array
        and _is_scalar_constant(loc.initializer)
        and loc.type.array_extent_exprs
    ):
        # Whole-array scalar initializer (Fortran ``real :: a(n) = 0.0`` or
        # ``= -9999.0``): build the array with its shape and broadcast the
        # scalar constant expression to every element.  An array-valued
        # initializer (array constructor) keeps the plain ``= ...`` form
        # below.
        fill = _render_expr(loc.initializer)
        extents = ", ".join(loc.type.array_extent_exprs)
        # Prefer the compile-time-lower-bounds form when every declared
        # lower bound is an integer literal: the bound becomes part of the
        # type and ``a(i)``'s ``(i - lower)`` constant-folds.  This form
        # uses the ``Array<T, R, Lower>(extents, fill)`` ctor that the
        # runtime grew alongside the static ``Lower`` NTTP.  Otherwise fall
        # back to the runtime ``(lower, extents, fill)`` ctor; default the
        # lower bounds to 1 when none were declared.
        static_cpp = _static_lower_cpp_type(loc)
        if static_cpp is not None:
            out.write(
                f"{pad}{prefix}{static_cpp} {loc.name}"
                f"{{{{{extents}}}, {fill}}};"
            )
        else:
            if loc.type.array_lower_bound_exprs:
                lowers = ", ".join(loc.type.array_lower_bound_exprs)
            else:
                lowers = ", ".join(["1"] * len(loc.type.array_extent_exprs))
            out.write(
                f"{pad}{prefix}{loc.type.cpp} {loc.name}"
                f"{{{{{lowers}}}, {{{extents}}}, {fill}}};"
            )
        _emit_trailing(out, loc.trailing_comments)
        return
    if loc.type.is_array and loc.initializer is None:
        if not loc.type.array_extent_exprs:
            # Deferred-shape (allocatable) array: default-construct
            # empty; an ALLOCATE statement sizes it later.
            out.write(f"{pad}{prefix}{loc.type.cpp} {loc.name};")
            _emit_trailing(out, loc.trailing_comments)
            return
        # Brace-init form ``Array<T,R> name{ {extents} };`` (runtime lb
        # defaults to 1, runtime explicit lb uses ``{ {lowers}, {extents} }``,
        # or compile-time lb spells the bound in the type and uses
        # ``{ {extents} }``).  Braces rather than parens so the same emit
        # works whether ``name`` is a local variable or a struct data
        # member (parens aren't allowed for default member initializers).
        extents = ", ".join(loc.type.array_extent_exprs)
        static_cpp = _static_lower_cpp_type(loc)
        if static_cpp is not None:
            out.write(f"{pad}{prefix}{static_cpp} {loc.name}{{{{{extents}}}}};")
        elif loc.type.array_lower_bound_exprs:
            lowers = ", ".join(loc.type.array_lower_bound_exprs)
            out.write(
                f"{pad}{prefix}{loc.type.cpp} {loc.name}"
                f"{{{{{lowers}}}, {{{extents}}}}};"
            )
        else:
            out.write(f"{pad}{prefix}{loc.type.cpp} {loc.name}{{{{{extents}}}}};")
        _emit_trailing(out, loc.trailing_comments)
        return
    if loc.type.is_pointer and not loc.type.is_array and loc.initializer is None:
        # Scalar pointer (T*) starts disassociated.
        out.write(f"{pad}{prefix}{loc.type.cpp} {loc.name} = nullptr;")
        _emit_trailing(out, loc.trailing_comments)
        return
    # An assumed-length CHARACTER local (only arises for an ENTRY-shared
    # dummy that isn't this entry's argument) is a character view, not a
    # ``std::string_view`` value — emit it as ``CharRef`` so substring
    # indexing ``s(i, j)`` and write-through still type-check.
    cpp = (
        "fortran::CharRef"
        if not loc.type.is_array and loc.type.cpp == "std::string_view"
        else loc.type.cpp
    )
    out.write(f"{pad}{prefix}{cpp} {loc.name}")
    if loc.initializer is not None:
        out.write(f" = {_render_expr(loc.initializer)}")
    else:
        # Value-initialize so scalars zero out, derived-type structs
        # default-construct, and FortranString fills with blanks —
        # matching Fortran's typical default-initialization behavior.
        out.write("{}")
    out.write(";")
    _emit_trailing(out, loc.trailing_comments)


def _ends_with_return(body: list[IRStatement]) -> bool:
    return bool(body) and isinstance(body[-1], IRReturn)


