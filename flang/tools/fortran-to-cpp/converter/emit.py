def _emit_statement(out: StringIO, stmt: IRStatement, *, indent: int) -> None:
    pad = "  " * indent
    if isinstance(stmt, IRComment):
        _emit_comment_block(out, stmt.comments, indent=indent)
        return
    if isinstance(stmt, IRAssignment):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(f"{pad}{_render_expr(stmt.target)} = {_render_expr(stmt.value)};")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRCall):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(f"{pad}{stmt.callee}(")
        out.write(", ".join(_render_expr(a) for a in stmt.args))
        out.write(");")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRPrint):
        if stmt.internal_unit is not None:
            _emit_internal_write(out, stmt, indent=indent)
            return
        if any(isinstance(it, IRImpliedDo) for it in stmt.items):
            # A formatted WRITE with implied-do items: expand the
            # implied-do at translation time when its bounds are integer
            # literals.  This lets the existing format renderer (with its
            # array-element overloads of fmt_E / fmt_F / ...) handle the
            # mixed item list as a flat sequence.  Falls back to the
            # list-directed implied-do emitter when no format is in play.
            if stmt.format is not None or stmt.format_expr is not None:
                expanded = _expand_constant_implied_dos(list(stmt.items))
                if expanded is not None:
                    stmt = IRPrint(
                        items=expanded,
                        stream=stmt.stream,
                        format=stmt.format,
                        format_expr=stmt.format_expr,
                        internal_unit=stmt.internal_unit,
                        leading_comments=stmt.leading_comments,
                        trailing_comments=stmt.trailing_comments,
                    )
                else:
                    # Implied-do bounds aren't compile-time constants:
                    # route through the runtime format interpreter, which
                    # cycles the format string over a runtime-built
                    # ``std::vector<FmtArg>`` so each item gets the right
                    # descriptor regardless of when the loop's count is
                    # known.  ``vformat_record`` then renders the cycled
                    # record into the output stream.
                    _emit_runtime_formatted_implied_do(
                        out, stmt, indent=indent
                    )
                    return
            else:
                _emit_io_with_implied_do(out, stmt, write=True, indent=indent)
                return
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(f"{pad}{stmt.stream}")
        suppress_nl = False
        if stmt.format_expr is not None:
            # Run-time FORMAT: interpret it against the items at run time.
            out.write(f" << {_render_format_record(stmt)}")
        elif stmt.format is not None:
            suppress_nl = _emit_formatted_chunks(out, stmt)
        else:
            # List-directed: separate items with a single space.
            for i, item in enumerate(stmt.items):
                if i > 0:
                    out.write(" << ' '")
                out.write(f" << {_render_expr(item)}")
        if suppress_nl:
            out.write(";")
        else:
            out.write(" << '\\n';")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRDirectRead):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(f"{pad}{{\n")
        out.write(
            f"{pad}  std::string _rec{{_units.read_record({stmt.unit_text}, "
            f"{_render_expr(stmt.rec)})}};\n"
        )
        for target, kind, off, width, dec in stmt.fields:
            tgt = _render_expr(target)
            if kind == "int":
                out.write(
                    f"{pad}  {tgt} = static_cast<std::int32_t>("
                    f"fortran::io::read_field_int(_rec, {off}, {width}));\n"
                )
            else:
                out.write(
                    f"{pad}  {tgt} = static_cast<float>("
                    f"fortran::io::read_field_real(_rec, {off}, {width}, {dec}));\n"
                )
        out.write(f"{pad}}}")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRDirectWrite):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        # Build the formatted record into a string, then place it at the
        # target record.  ``_emit_formatted_chunks`` is duck-typed on
        # ``.format`` / ``.items``, which IRDirectWrite also carries.
        out.write(f"{pad}{{\n")
        out.write(f"{pad}  std::ostringstream _wrec;\n")
        out.write(f"{pad}  _wrec")
        _emit_formatted_chunks(out, stmt)  # writes " << ..."
        out.write(";\n")
        out.write(
            f"{pad}  _units.write_record({stmt.unit_text}, "
            f"{_render_expr(stmt.rec)}, _wrec.str());\n"
        )
        out.write(f"{pad}}}")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRUnformattedDirectWrite):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        # Pack each item onto a raw byte buffer, then place it at the
        # target record (zero-padded / truncated to RECL by the runtime).
        out.write(f"{pad}{{\n")
        out.write(f"{pad}  std::vector<std::byte> _wrec;\n")
        for item in stmt.items:
            _emit_unformatted_item(out, item, "_wrec", read=False, indent=indent + 1)
        out.write(
            f"{pad}  _units.write_record_raw({stmt.unit_text}, "
            f"{_render_expr(stmt.rec)}, _wrec);\n"
        )
        out.write(f"{pad}}}")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRUnformattedDirectRead):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        # Fetch the whole record as raw bytes, then unpack each item.
        out.write(f"{pad}{{\n")
        out.write(
            f"{pad}  auto _rrec = _units.read_record_raw("
            f"{stmt.unit_text}, {_render_expr(stmt.rec)});\n"
        )
        out.write(f"{pad}  std::size_t _roff = 0;\n")
        for item in stmt.items:
            _emit_unformatted_item(out, item, "_rrec", read=True, indent=indent + 1)
        out.write(f"{pad}}}")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRInquire):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        # One ``_units.inquire_by_*`` call, then per-output field copies.
        out.write(f"{pad}{{\n")
        call = (
            "inquire_by_unit" if stmt.selector_kind == "unit"
            else "inquire_by_file"
        )
        out.write(
            f"{pad}  auto _inq = _units.{call}({_render_expr(stmt.selector)});\n"
        )
        for field, target in stmt.outputs:
            out.write(f"{pad}  {_render_expr(target)} = _inq.{field};\n")
        out.write(f"{pad}}}")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRFilePosition):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(
            f"{pad}_units.{stmt.op}({_render_expr(stmt.unit)});"
        )
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRRead):
        if stmt.internal_unit is not None:
            _emit_internal_read(out, stmt, indent=indent)
            return
        if stmt.fields is not None and stmt.unit_text is not None:
            _emit_formatted_sequential_read(out, stmt, indent=indent)
            return
        if any(isinstance(it, IRImpliedDo) for it in stmt.items):
            _emit_io_with_implied_do(out, stmt, write=False, indent=indent)
            return
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        if not stmt.items:
            # READ(unit, *) with no item list — Fortran reads-and-discards
            # a whole record.  In C++ that means skip to and past the next
            # newline on the stream.
            out.write(
                f"{pad}{stmt.stream}.ignore("
                f"std::numeric_limits<std::streamsize>::max(), '\\n');"
            )
            _emit_trailing(out, stmt.trailing_comments)
            return
        # List-directed READ: route each item through ``read_list_item``
        # so Fortran's "current value preserved on /" semantics survive
        # C++11's "zero target on failure" behavior.  Short-circuit via
        # ``&&`` so once one item fails (e.g. a ``/`` terminator), the
        # remaining items keep their previous values rather than each
        # consuming further input.
        item_calls = " && ".join(
            f"fortran::io::read_list_item({stmt.stream}, {_render_expr(item)})"
            for item in stmt.items
        )
        if item_calls:
            out.write(f"{pad}(void)({item_calls});")
        # Once the items are filled (or terminated), advance to the next
        # record so the next READ starts on a fresh line.  Clear the
        # failbit too, but preserve eofbit so a well-formed EOF still
        # trips ``END=``-labelled jumps.
        out.write(
            f"\n{pad}if ({stmt.stream}.fail() && !{stmt.stream}.eof()) "
            f"{stmt.stream}.clear();"
        )
        out.write(
            f"\n{pad}{stmt.stream}.ignore("
            f"std::numeric_limits<std::streamsize>::max(), '\\n');"
        )
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRStop):
        _emit_stop(out, stmt, indent=indent)
        return
    if isinstance(stmt, IRAllocate):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        if not stmt.cpp_type:
            raise ConversionError(
                "ALLOCATE", note=f"could not resolve type of {stmt.obj!r}"
            )
        extents = ", ".join(_render_expr(e) for e in stmt.extents)
        if stmt.lowers:
            lowers = ", ".join(_render_expr(e) for e in stmt.lowers)
            out.write(
                f"{pad}{stmt.obj} = {stmt.cpp_type}({{{lowers}}}, {{{extents}}});"
            )
        else:
            out.write(f"{pad}{stmt.obj} = {stmt.cpp_type}({{{extents}}});")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRDeallocate):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(f"{pad}{stmt.obj}.deallocate();")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRPointerAssign):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        if stmt.target is None:
            # nullify / => null()
            rhs = "{}" if stmt.is_array else "nullptr"
            out.write(f"{pad}{stmt.pointer} = {rhs};")
        elif stmt.is_array:
            # Fortran ``p => target(...)``: rebind ``p``'s view to the
            # target's storage (share, don't copy elements).  Use the
            # ArrayRef rebind method explicitly because ``=`` now does
            # element-wise copy (the IRI ``read_data_SD`` semantics).
            out.write(
                f"{pad}{stmt.pointer}.rebind({_render_expr(stmt.target)});"
            )
        else:
            rhs = f"&{_render_expr(stmt.target)}"  # take target's address
            out.write(f"{pad}{stmt.pointer} = {rhs};")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRReturn):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        if stmt.value is None:
            out.write(f"{pad}return;")
        else:
            out.write(f"{pad}return {_render_expr(stmt.value)};")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRIf):
        _emit_if(out, stmt, indent=indent)
        return
    if isinstance(stmt, IRDo):
        _emit_do(out, stmt, indent=indent)
        return
    if isinstance(stmt, IRWhile):
        _emit_while(out, stmt, indent=indent)
        return
    if isinstance(stmt, IRSelectCase):
        _emit_select_case(out, stmt, indent=indent)
        return
    if isinstance(stmt, IRCycle):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(f"{pad}continue;")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRExit):
        _emit_comment_block(out, stmt.leading_comments, indent=indent)
        out.write(f"{pad}break;")
        _emit_trailing(out, stmt.trailing_comments)
        return
    if isinstance(stmt, IRBlock):
        _emit_block(out, stmt, indent=indent)
        return
    if isinstance(stmt, IRUnsupported):
        _emit_unsupported(out, stmt, indent=indent)
        return
    raise ConversionError(
        type(stmt).__name__, note="unhandled IR statement"
    )


def _emit_block(out: StringIO, node: IRBlock, *, indent: int) -> None:
    pad = "  " * indent
    _emit_comment_block(out, node.leading_comments, indent=indent)
    out.write(f"{pad}{{\n")
    # ASSOCIATE bindings (auto&& binds to lvalue or rvalue selectors).
    for name, expr in node.bindings:
        out.write(f"{pad}  auto&& {name} = {_render_expr(expr)};\n")
    # BLOCK local declarations.
    for loc in node.locals:
        _emit_local(out, loc, indent=indent + 1)
    for s in node.body:
        _emit_statement(out, s, indent=indent + 1)
    out.write(f"{pad}}}\n")
    _emit_trailing(out, node.trailing_comments)


def _expand_constant_implied_dos(items: list[IRExpr]) -> list[IRExpr] | None:
    """Expand IRImpliedDo entries with integer-literal bounds into a flat
    item list, substituting the loop variable with each integer value.

    Returns the expanded list, or ``None`` if any implied-do has bounds
    the translator can't resolve at compile time."""
    from .transform import map_expr

    def lit_int(e: IRExpr) -> int | None:
        if isinstance(e, IRLiteral):
            try:
                return int(e.cpp_text)
            except ValueError:
                return None
        return None

    def substitute(expr: IRExpr, var: str, value: int) -> IRExpr:
        def swap(e: IRExpr) -> IRExpr:
            if isinstance(e, IRName) and e.name == var:
                return IRLiteral(cpp_text=str(value))
            return e
        return map_expr(expr, swap)

    out: list[IRExpr] = []
    for it in items:
        if isinstance(it, IRImpliedDo):
            lo = lit_int(it.lower)
            hi = lit_int(it.upper)
            step = lit_int(it.step) if it.step is not None else 1
            if lo is None or hi is None or step is None or step == 0:
                return None
            inner_expanded = _expand_constant_implied_dos(list(it.items))
            if inner_expanded is None:
                return None
            i = lo
            while (step > 0 and i <= hi) or (step < 0 and i >= hi):
                for sub in inner_expanded:
                    out.append(substitute(sub, it.var, i))
                i += step
        else:
            out.append(it)
    return out


def _emit_formatted_chunks(out: StringIO, stmt: "IRPrint") -> bool:
    """Emit the ``<< ...`` chain for a format-directed print/write.

    A format the parser can't model is an error, not a silent
    degradation: list-directed output would print the right values with
    the wrong layout, which is exactly the kind of quietly-wrong result
    we refuse to emit.

    Returns ``True`` if the FORMAT requested newline suppression (``$``)
    so the caller knows to skip its trailing ``<< '\\n'``.
    """
    from .format import FormatParseError, render_format

    assert stmt.format is not None
    item_exprs = [_render_expr(it) for it in stmt.items]
    try:
        chunks, suppress_nl = render_format(stmt.format, item_exprs)
    except FormatParseError as exc:
        raise ConversionError(
            "FORMAT", note=str(exc), source=stmt.format
        ) from exc
    for chunk in chunks:
        out.write(f" << {chunk}")
    return suppress_nl


def _emit_internal_write(out: StringIO, stmt: "IRPrint", *, indent: int) -> None:
    """Internal-file write: build the formatted record in a string stream
    and assign it to the character-variable unit (no trailing newline —
    a scalar character unit holds exactly one record)."""
    pad = "  " * indent
    _emit_comment_block(out, stmt.leading_comments, indent=indent)
    unit = _render_expr(stmt.internal_unit)
    if stmt.format_expr is not None:
        # Run-time FORMAT: build the record via the runtime interpreter and
        # assign it directly (no intermediate ostringstream needed).
        out.write(f"{pad}{unit} = {_render_format_record(stmt)};")
        _emit_trailing(out, stmt.trailing_comments)
        return
    out.write(f"{pad}{{\n")
    out.write(f"{pad}  std::ostringstream _ftn_os;\n")
    out.write(f"{pad}  _ftn_os")
    if stmt.format is not None:
        _emit_formatted_chunks(out, stmt)
    else:
        for i, item in enumerate(stmt.items):
            if i > 0:
                out.write(" << ' '")
            out.write(f" << {_render_expr(item)}")
    out.write(";\n")
    out.write(f"{pad}  {unit} = _ftn_os.str();\n")
    out.write(f"{pad}}}")
    _emit_trailing(out, stmt.trailing_comments)


def _render_format_record(stmt: "IRPrint") -> str:
    """Render a ``fortran::io::format_record(fmt, items...)`` call for a
    run-time (non-constant) FORMAT.  The first argument is the format
    string expression; the rest are the output items, flattened."""
    assert stmt.format_expr is not None
    args = [_render_expr(stmt.format_expr)]
    args.extend(_render_expr(it) for it in stmt.items)
    return f"fortran::io::format_record({', '.join(args)})"


def _emit_formatted_sequential_read(
    out: StringIO, stmt: "IRRead", *, indent: int
) -> None:
    """Sequential ``READ(unit, fmt)`` with a fixed-width FORMAT (e.g.
    ``FORMAT(3I3,9I3,I3,3F5.1)``).  Reads one record via ``getline`` per
    format cycle and slices each item by its pre-resolved offset/width
    using ``read_field_int`` / ``read_field_real`` -- matching Fortran's
    column-positional semantics instead of the ``>>`` chain's
    space-tokenizing.

    When the item list exceeds the format's data-descriptor count the
    format cycles to a new record (MSIS-86 reads its 1464-element
    coefficient table with ``FORMAT(1X,5E13.6)`` over 293 lines).
    Each record in ``stmt.fields`` is one such getline + per-field slice
    block."""
    assert stmt.fields is not None and stmt.unit_text is not None
    pad = "  " * indent
    _emit_comment_block(out, stmt.leading_comments, indent=indent)
    out.write(f"{pad}{{\n")
    out.write(f"{pad}  std::string _rec;\n")
    for record in stmt.fields:
        out.write(
            f"{pad}  std::getline(_units.in({stmt.unit_text}), _rec);\n"
        )
        for target, kind, off, width, dec in record:
            tgt = _render_expr(target)
            if kind == "int":
                out.write(
                    f"{pad}  {tgt} = static_cast<std::int32_t>("
                    f"fortran::io::read_field_int(_rec, {off}, {width}));\n"
                )
            else:
                out.write(
                    f"{pad}  {tgt} = static_cast<float>("
                    f"fortran::io::read_field_real(_rec, {off}, {width}, {dec}));\n"
                )
    out.write(f"{pad}}}")
    _emit_trailing(out, stmt.trailing_comments)


def _emit_internal_read(out: StringIO, stmt: "IRRead", *, indent: int) -> None:
    """Internal-file read: parse items from the character-variable unit
    via a string stream."""
    pad = "  " * indent
    _emit_comment_block(out, stmt.leading_comments, indent=indent)
    unit = _render_expr(stmt.internal_unit)
    out.write(f"{pad}{{\n")
    out.write(
        f"{pad}  std::istringstream _ftn_is{{std::string{{std::string_view{{{unit}}}}}}};\n"
    )
    out.write(f"{pad}  _ftn_is")
    for item in stmt.items:
        out.write(f" >> {_render_expr(item)}")
    out.write(";\n")
    out.write(f"{pad}}}")
    _emit_trailing(out, stmt.trailing_comments)


def _emit_unformatted_item(
    out, item, rec_var: str, *, read: bool, indent: int
) -> None:
    """Emit one item of an unformatted direct READ/WRITE.

    Plain items become a single ``take_bytes`` / ``append_bytes`` call.
    An implied-do becomes a runtime for-loop that iterates over its
    inner items -- mirrors the order Fortran would serialize them in
    (innermost loop fastest, items in declaration order)."""
    pad = "  " * indent
    if isinstance(item, IRImpliedDo):
        lo = _render_expr(item.lower)
        hi = _render_expr(item.upper)
        step = _render_expr(item.step) if item.step is not None else "1"
        v = item.var
        out.write(
            f"{pad}for (std::int32_t {v} = {lo}; {v} <= {hi}; {v} += {step}) {{\n"
        )
        for inner in item.items:
            _emit_unformatted_item(
                out, inner, rec_var, read=read, indent=indent + 1
            )
        out.write(f"{pad}}}\n")
        return
    if read:
        out.write(
            f"{pad}_roff = fortran::io::take_bytes({rec_var}, _roff, "
            f"{_render_expr(item)});\n"
        )
    else:
        out.write(
            f"{pad}fortran::io::append_bytes({rec_var}, "
            f"{_render_expr(item)});\n"
        )


def _emit_runtime_formatted_implied_do(
    out: StringIO, stmt: "IRPrint", *, indent: int
) -> None:
    """Emit a formatted WRITE with runtime-bounded implied-do items via
    the runtime format interpreter.  Builds a ``std::vector<FmtArg>``
    at run time (scalars push one arg, implied-do items push one per
    iteration), then routes through ``vformat_record(fmt, args)`` which
    cycles the format over the args.
    """
    pad = "  " * indent
    _emit_comment_block(out, stmt.leading_comments, indent=indent)
    out.write(f"{pad}{{\n")
    out.write(f"{pad}  std::vector<fortran::io::FmtArg> _args;\n")

    def push_item(item, ind: int) -> None:
        ipad = "  " * ind
        if isinstance(item, IRImpliedDo):
            var = item.var
            lo = _render_expr(item.lower)
            hi = _render_expr(item.upper)
            step = _render_expr(item.step) if item.step is not None else "1"
            cond = (
                f"{var} <= {hi}" if step == "1"
                else f"({step} >= 0 ? {var} <= {hi} : {var} >= {hi})"
            )
            incr = f"++{var}" if step == "1" else f"{var} += {step}"
            out.write(
                f"{ipad}for (fortran::index_t {var} = {lo}; "
                f"{cond}; {incr}) {{\n"
            )
            for sub in item.items:
                push_item(sub, ind + 1)
            out.write(f"{ipad}}}\n")
        else:
            rendered = _render_expr(item)
            out.write(
                f"{ipad}_args.push_back("
                f"fortran::io::make_fmt_arg({rendered}));\n"
            )

    for it in stmt.items:
        push_item(it, indent + 1)
    if stmt.format_expr is not None:
        fmt_expr = _render_expr(stmt.format_expr)
    else:
        from .format import _cpp_string_literal as _csl
        fmt_expr = _csl(stmt.format)
    out.write(
        f"{pad}  {stmt.stream} << "
        f"fortran::io::vformat_record({fmt_expr}, _args) << '\\n';\n"
    )
    out.write(f"{pad}}}")
    _emit_trailing(out, stmt.trailing_comments)


def _emit_io_with_implied_do(out, stmt, *, write: bool, indent: int) -> None:
    """Emit a print/read whose item list contains an implied-do, as a
    sequence of statements (plain items inline, implied-do items as
    loops).  Used only for the list-directed forms."""
    pad = "  " * indent
    _emit_comment_block(out, stmt.leading_comments, indent=indent)
    stream = stmt.stream
    op = "<<" if write else ">>"

    def emit_item(item, ind: int) -> None:
        ipad = "  " * ind
        if isinstance(item, IRImpliedDo):
            var = item.var
            lo = _render_expr(item.lower)
            hi = _render_expr(item.upper)
            step = _render_expr(item.step) if item.step is not None else "1"
            cond = f"{var} <= {hi}" if step == "1" else (
                f"({step} >= 0 ? {var} <= {hi} : {var} >= {hi})"
            )
            incr = f"++{var}" if step == "1" else f"{var} += {step}"
            out.write(
                f"{ipad}for (fortran::index_t {var} = {lo}; {cond}; {incr}) {{\n"
            )
            for sub in item.items:
                emit_item(sub, ind + 1)
            out.write(f"{ipad}}}\n")
        else:
            rendered = _render_expr(item)
            if write:
                out.write(f"{ipad}{stream} {op} {rendered} {op} ' ';\n")
            else:
                out.write(f"{ipad}{stream} {op} {rendered};\n")

    for it in stmt.items:
        emit_item(it, indent)
    if write:
        out.write(f"{pad}{stream} << '\\n';\n")


def _emit_stop(out: StringIO, stmt: "IRStop", *, indent: int) -> None:
    pad = "  " * indent
    _emit_comment_block(out, stmt.leading_comments, indent=indent)
    # Determine the exit code expression.
    if stmt.code is not None:
        code = _render_expr(stmt.code)
    else:
        code = "1" if stmt.is_error else "0"
    if stmt.message is not None:
        escaped = stmt.message.replace("\\", "\\\\").replace('"', '\\"')
        # Fortran prints the stop message; mirror that on stderr.
        out.write(f'{pad}{{ std::cerr << "{escaped}" << \'\\n\'; '
                  f"std::exit({code}); }}")
    else:
        out.write(f"{pad}std::exit({code});")
    _emit_trailing(out, stmt.trailing_comments)


def _emit_while(out: StringIO, node: IRWhile, *, indent: int) -> None:
    pad = "  " * indent
    _emit_comment_block(out, node.leading_comments, indent=indent)
    out.write(f"{pad}while ({_render_expr(node.condition)}) {{\n")
    for s in node.body:
        _emit_statement(out, s, indent=indent + 1)
    out.write(f"{pad}}}\n")
    _emit_trailing(out, node.trailing_comments)


def _emit_select_case(
    out: StringIO, node: IRSelectCase, *, indent: int
) -> None:
    """Lower SELECT CASE.

    When every clause is a list of literal integer values and/or bounded
    literal-integer ranges of modest total width, emit a real C++
    ``switch`` -- a dense integer SELECT CASE compiles to a jump-table
    rather than the sequential compare chain of an ``if`` chain.
    Otherwise (CHARACTER / LOGICAL selectors, open-ended ranges, wide
    ranges, non-literal bounds) fall back to the if-chain form, which
    handles every case shape Fortran allows.
    """
    if _switch_eligible(node):
        _emit_select_case_switch(out, node, indent=indent)
        return
    _emit_select_case_ifchain(out, node, indent=indent)


# Cap on total case-label expansion for ranged CASE forms.  CASE (1:5) -> 5
# labels, CASE (1, 7, 10:12) -> 5 labels, etc.  Picked so a typical kind-code
# selector (a few dozen values) takes the switch path while a pathological
# CASE (1:1000000) doesn't blow up the .cpp.
_SWITCH_LABEL_BUDGET = 64


def _int_literal_value(expr: IRExpr) -> int | None:
    """Return the integer value of a literal expression, or None."""
    if isinstance(expr, IRLiteral):
        t = expr.cpp_text.strip()
        # Allow a leading sign and an optional kind suffix.
        if t.startswith(("-", "+")):
            sign, body = t[0], t[1:]
        else:
            sign, body = "+", t
        # Strip a C++ literal suffix (``42LL``, ``42L``, ``42U`` etc.).
        while body and body[-1] in "uUlL":
            body = body[:-1]
        if body.isdigit():
            return int(sign + body)
    return None


def _switch_eligible(node: IRSelectCase) -> bool:
    """A SELECT CASE is switch-eligible when every match is a literal
    integer and total label count stays within the budget."""
    if not node.clauses:
        return False
    total = 0
    for clause in node.clauses:
        for v in clause.values:
            if _int_literal_value(v) is None:
                return False
            total += 1
        for lo, hi in clause.ranges:
            lo_v = _int_literal_value(lo) if lo is not None else None
            hi_v = _int_literal_value(hi) if hi is not None else None
            # Open-ended ranges can't be enumerated.
            if lo_v is None or hi_v is None:
                return False
            if hi_v < lo_v:
                # An empty range is fine but adds 0 labels.
                continue
            total += hi_v - lo_v + 1
            if total > _SWITCH_LABEL_BUDGET:
                return False
    return total > 0


def _emit_select_case_switch(
    out: StringIO, node: IRSelectCase, *, indent: int
) -> None:
    pad = "  " * indent
    body_pad = pad + "  "
    case_pad = body_pad + "  "
    _emit_comment_block(out, node.leading_comments, indent=indent)
    out.write(f"{pad}switch ({_render_expr(node.selector)}) {{\n")
    for clause in node.clauses:
        labels: list[int] = []
        for v in clause.values:
            iv = _int_literal_value(v)
            assert iv is not None  # _switch_eligible guarantees this
            labels.append(iv)
        for lo, hi in clause.ranges:
            assert lo is not None and hi is not None
            lo_v = _int_literal_value(lo)
            hi_v = _int_literal_value(hi)
            assert lo_v is not None and hi_v is not None
            labels.extend(range(lo_v, hi_v + 1))
        for label in labels:
            out.write(f"{body_pad}case {label}:\n")
        for s in clause.body:
            _emit_statement(out, s, indent=indent + 2)
        out.write(f"{case_pad}break;\n")
    if node.default_body is not None:
        out.write(f"{body_pad}default:\n")
        for s in node.default_body:
            _emit_statement(out, s, indent=indent + 2)
        out.write(f"{case_pad}break;\n")
    out.write(f"{pad}}}\n")
    _emit_trailing(out, node.trailing_comments)


def _emit_select_case_ifchain(
    out: StringIO, node: IRSelectCase, *, indent: int
) -> None:
    """Fallback for non-integral selectors, open-ended ranges, etc."""
    pad = "  " * indent
    _emit_comment_block(out, node.leading_comments, indent=indent)
    selector_text = _render_expr(node.selector)
    sel = selector_text
    opened_scope = not _is_simple_selector(node.selector)
    if opened_scope:
        # Bind the selector to a local so it's evaluated exactly once.
        out.write(f"{pad}{{\n")
        out.write(f"{pad}  const auto _sel = {selector_text};\n")
        sel = "_sel"
        inner_pad = pad + "  "
        body_indent = indent + 2
    else:
        inner_pad = pad
        body_indent = indent + 1

    first = True
    for clause in node.clauses:
        cond = _case_condition(sel, clause)
        if first:
            out.write(f"{inner_pad}if ({cond}) {{\n")
            first = False
        else:
            out.write(f" else if ({cond}) {{\n")
        for s in clause.body:
            _emit_statement(out, s, indent=body_indent)
        out.write(f"{inner_pad}}}")
    if node.default_body is not None:
        if first:
            # No case clauses, only a default — emit a bare block.
            out.write(f"{inner_pad}{{\n")
        else:
            out.write(" else {\n")
        for s in node.default_body:
            _emit_statement(out, s, indent=body_indent)
        out.write(f"{inner_pad}}}\n")
    else:
        out.write("\n")
    if opened_scope:
        out.write(f"{pad}}}\n")
    _emit_trailing(out, node.trailing_comments)


def _is_simple_selector(expr: IRExpr) -> bool:
    return isinstance(expr, (IRName, IRLiteral))


def _case_condition(sel: str, clause: "IRCaseClause") -> str:
    """Build the boolean test for one case clause."""
    parts: list[str] = []
    for v in clause.values:
        parts.append(f"{sel} == {_render_expr(v)}")
    for lo, hi in clause.ranges:
        if lo is not None and hi is not None:
            parts.append(f"({sel} >= {_render_expr(lo)} && {sel} <= {_render_expr(hi)})")
        elif lo is not None:
            parts.append(f"{sel} >= {_render_expr(lo)}")
        elif hi is not None:
            parts.append(f"{sel} <= {_render_expr(hi)}")
    return " || ".join(parts) if parts else "false"


def _emit_if(out: StringIO, node: IRIf, *, indent: int) -> None:
    pad = "  " * indent
    _emit_comment_block(out, node.leading_comments, indent=indent)
    for i, (cond, body) in enumerate(node.branches):
        keyword = "if" if i == 0 else "else if"
        out.write(f"{pad}{keyword} ({_render_expr(cond)}) {{\n")
        for s in body:
            _emit_statement(out, s, indent=indent + 1)
        out.write(f"{pad}}}")
        if i + 1 < len(node.branches) or node.else_body is not None:
            out.write(" ")
        else:
            out.write("\n")
    if node.else_body is not None:
        out.write("else {\n")
        for s in node.else_body:
            _emit_statement(out, s, indent=indent + 1)
        out.write(f"{pad}}}\n")
    _emit_trailing(out, node.trailing_comments)


def _emit_do(out: StringIO, node: IRDo, *, indent: int) -> None:
    pad = "  " * indent
    _emit_comment_block(out, node.leading_comments, indent=indent)
    var = node.var
    decl = "fortran::index_t " if node.declare else ""
    lo = _render_expr(node.lower)
    hi = _render_expr(node.upper)
    step = _render_expr(node.step) if node.step is not None else "1"
    # For the common step==1 case, write a clean ``i <= hi`` form.
    if step == "1":
        out.write(
            f"{pad}for ({decl}{var} = {lo}; {var} <= {hi}; ++{var}) {{\n"
        )
    else:
        out.write(
            f"{pad}for ({decl}{var} = {lo}; "
            f"({step} >= 0 ? {var} <= {hi} : {var} >= {hi}); "
            f"{var} += {step}) {{\n"
        )
    for s in node.body:
        _emit_statement(out, s, indent=indent + 1)
    out.write(f"{pad}}}\n")
    _emit_trailing(out, node.trailing_comments)


def _emit_unsupported(
    out: StringIO, stmt: IRUnsupported, *, indent: int
) -> None:
    # An IRUnsupported reaching emit means an earlier pass couldn't model
    # the construct.  Fail loudly rather than write a // TODO placeholder.
    raise ConversionError(stmt.kind, note=stmt.note, source=stmt.source_text)


